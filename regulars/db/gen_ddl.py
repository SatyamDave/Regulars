"""Print the Postgres DDL for ``regulars.db.schema.metadata``.

Regenerate the checked-in migration with::

    uv run python -m regulars.db.gen_ddl > regulars/db/migrations/0001_initial.sql

``tests/db/test_schema.py`` fails if the file drifts from this output.
"""

from __future__ import annotations

import sys
from typing import TextIO

from sqlalchemy.engine import make_url
from sqlalchemy.schema import CreateIndex, CreateTable

from regulars.db.schema import PERSONA_IMMUTABLE_DDL, metadata

HEADER = (
    "-- Regulars initial schema (technical-architecture.md §1, §9).\n"
    "-- Generated by `uv run python -m regulars.db.gen_ddl`; do not edit by hand.\n"
)


def render_postgres_ddl() -> str:
    # Compile-only: no driver is imported or connected.
    dialect = make_url("postgresql://").get_dialect()()
    statements: list[str] = []
    for table in metadata.sorted_tables:
        statements.append(CreateTable(table).compile(dialect=dialect).string.strip())
        for index in sorted(table.indexes, key=lambda ix: ix.name or ""):
            statements.append(CreateIndex(index).compile(dialect=dialect).string.strip())
    statements.extend(PERSONA_IMMUTABLE_DDL["postgresql"])
    body = ";\n\n".join(statements) + ";\n"
    # SQLAlchemy leaves a trailing space after each column separator; keep the file tidy.
    return HEADER + "\n" + "\n".join(line.rstrip() for line in body.splitlines()) + "\n"


def main(out: TextIO = sys.stdout) -> None:
    out.write(render_postgres_ddl())


if __name__ == "__main__":
    main()
