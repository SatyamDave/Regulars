"""Print the Postgres DDL for ``regulars.db.schema.metadata``.

Regenerate the checked-in migration with::

    uv run python -m regulars.db.gen_ddl > regulars/db/migrations/0001_initial.sql

``tests/db/test_schema.py`` fails if the file drifts from this output. Tables added after 0001
(technical-architecture.md §1) are tagged ``info={"migration": "0002"}`` etc. in ``schema.py`` so
they are excluded from the default (0001) rendering; print a later migration's tables on their
own with ``--migration <id>``, e.g.::

    uv run python -m regulars.db.gen_ddl --migration 0002 \\
        > regulars/db/migrations/0002_bot_state.sql
"""

from __future__ import annotations

import argparse
import sys
from typing import TextIO

from sqlalchemy import Table
from sqlalchemy.engine import make_url
from sqlalchemy.schema import CreateIndex, CreateTable

from regulars.db.schema import PERSONA_IMMUTABLE_DDL, metadata

HEADER = (
    "-- Regulars initial schema (technical-architecture.md §1, §9).\n"
    "-- Generated by `uv run python -m regulars.db.gen_ddl`; do not edit by hand.\n"
)

MIGRATION_HEADER = (
    "-- Regulars migration {migration}: bot runtime + ledger state.\n"
    "-- Generated by `uv run python -m regulars.db.gen_ddl --migration {migration}`; "
    "do not edit by hand.\n"
)


def _tables_for_migration(migration: str | None) -> list[Table]:
    """Tables in FK-dependency order, filtered to ``migration`` (``None`` = the 0001 tables)."""
    return [table for table in metadata.sorted_tables if table.info.get("migration") == migration]


def _render(tables: list[Table], header: str, *, include_persona_trigger: bool) -> str:
    dialect = make_url("postgresql://").get_dialect()()  # compile-only: no driver, no connection
    statements: list[str] = []
    for table in tables:
        statements.append(CreateTable(table).compile(dialect=dialect).string.strip())
        for index in sorted(table.indexes, key=lambda ix: ix.name or ""):
            statements.append(CreateIndex(index).compile(dialect=dialect).string.strip())
    if include_persona_trigger:
        statements.extend(PERSONA_IMMUTABLE_DDL["postgresql"])
    body = ";\n\n".join(statements) + ";\n"
    # SQLAlchemy leaves a trailing space after each column separator; keep the file tidy.
    return header + "\n" + "\n".join(line.rstrip() for line in body.splitlines()) + "\n"


def render_postgres_ddl() -> str:
    """The 0001 tables only (untagged); this is what ``tests/db/test_schema.py`` pins."""
    return _render(_tables_for_migration(None), HEADER, include_persona_trigger=True)


def render_migration_ddl(migration: str) -> str:
    """The tables tagged ``info={"migration": migration}`` in ``schema.py``."""
    tables = _tables_for_migration(migration)
    if not tables:
        raise ValueError(f"no tables are tagged migration {migration!r}")
    header = MIGRATION_HEADER.format(migration=migration)
    return _render(tables, header, include_persona_trigger=False)


def main(argv: list[str] | None = None, out: TextIO = sys.stdout) -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--migration", default=None, help="print only this migration's tables")
    args = parser.parse_args(argv)
    if args.migration is None:
        out.write(render_postgres_ddl())
    else:
        out.write(render_migration_ddl(args.migration))


if __name__ == "__main__":
    main()
